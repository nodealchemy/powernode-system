# frozen_string_literal: true

require "rails_helper"

RSpec.describe "Operator API — Node Modules rollback", type: :request do
  let(:account) { create(:account) }
  let(:other_account) { create(:account) }
  let(:user) { user_with_permissions("system.modules.read", "system.modules.update", account: account) }
  let(:headers) { auth_headers_for(user).merge("Content-Type" => "application/json") }

  let(:platform) { create(:system_node_platform, account: account) }
  let(:category) { create(:system_node_module_category, account: account) }
  let(:node_module) do
    create(:system_node_module, account: account, node_platform: platform,
           category: category, variety: "subscription", name: "test-mod")
  end

  # Stand up two versions deterministically. Using update_columns to bypass
  # NodeModule's after_update :auto_create_version callback — the callback's
  # behavior is exercised elsewhere; here we want explicit control of the
  # version chain so rollback's "go to previous" semantics is unambiguous.
  let!(:v1) do
    v = create(:system_node_module_version, node_module: node_module,
               version_number: 1, file_spec: { "a" => "1" })
    node_module.update_columns(current_version_id: v.id, current_version_number: 1,
                               file_spec: { "a" => "1" })
    v
  end
  let!(:v2) do
    v = create(:system_node_module_version, node_module: node_module,
               version_number: 2, file_spec: { "b" => "2" })
    node_module.update_columns(current_version_id: v.id, current_version_number: 2,
                               file_spec: { "b" => "2" })
    v
  end

  describe "POST /api/v1/system/node_modules/:id/rollback" do
    context "default behavior (no target_version_id)" do
      it "rolls back to the immediately previous version" do
        baseline = node_module.versions.maximum(:version_number)
        post "/api/v1/system/node_modules/#{node_module.id}/rollback", headers: headers
        expect(response).to have_http_status(:ok)

        body = JSON.parse(response.body)
        expect(body.dig("data", "new_version", "version_number")).to eq(baseline + 1)
        expect(body.dig("data", "node_module", "file_spec")).to eq({ "a" => "1" })
      end

      # IMP-b7abf6c777da — the pointer moves through the promote seam, so the
      # rollback arms a restart. Read the COLUMN and the arm, not the body.
      it "promotes the rollback version through NodeModule#promote_to_version! and arms restart_after_update" do
        node_module.update_columns(config: {
          "restart_after_update" => [ { "module" => "powernode-hub-backend", "services" => [ "rails" ] } ]
        })
        v1.update_columns(config: node_module.config)
        v2.update_columns(config: node_module.config)
        expect(node_module.reload.current_version_id).to eq(v2.id)

        post "/api/v1/system/node_modules/#{node_module.id}/rollback", headers: headers
        expect(response).to have_http_status(:ok)

        new_id = JSON.parse(response.body).dig("data", "new_version", "id")
        node_module.reload
        expect(node_module.current_version_id).to eq(new_id)
        expect(node_module.current_version_number).to eq(node_module.versions.maximum(:version_number))
        expect(::System::RestartAfterUpdate.armed?(::System::NodeModuleVersion.find(new_id))).to be true
      end
    end

    context "with target_version_id" do
      it "rolls back to the specified version" do
        baseline = node_module.versions.maximum(:version_number)

        post "/api/v1/system/node_modules/#{node_module.id}/rollback",
             params: { target_version_id: v1.id }.to_json, headers: headers

        expect(response).to have_http_status(:ok)
        body = JSON.parse(response.body)
        expect(body.dig("data", "new_version", "version_number")).to eq(baseline + 1)
        expect(node_module.reload.file_spec).to eq({ "a" => "1" })
      end

      it "404s when target_version_id is unknown" do
        post "/api/v1/system/node_modules/#{node_module.id}/rollback",
             params: { target_version_id: SecureRandom.uuid }.to_json, headers: headers

        expect(response).to have_http_status(:not_found)
      end
    end

    context "lock state" do
      it "422s when the module is locked" do
        node_module.update!(lock_spec: true)

        post "/api/v1/system/node_modules/#{node_module.id}/rollback", headers: headers

        expect(response).to have_http_status(:unprocessable_content)
        expect(JSON.parse(response.body)["error"]).to match(/locked/i)
      end
    end

    context "cross-account isolation" do
      it "404s for a module in another account" do
        foreign_platform = create(:system_node_platform, account: other_account)
        foreign_cat = create(:system_node_module_category, account: other_account)
        foreign_module = create(:system_node_module, account: other_account,
                                node_platform: foreign_platform, category: foreign_cat,
                                variety: "subscription", name: "foreign")

        post "/api/v1/system/node_modules/#{foreign_module.id}/rollback", headers: headers

        expect(response).to have_http_status(:not_found)
      end
    end

    context "no previous version" do
      it "422s when the module has no history to roll back to" do
        lone = create(:system_node_module, account: account, node_platform: platform,
                      category: category, variety: "subscription", name: "lone-mod")
        # Single version + no prior — rollback_to_previous raises RollbackError
        only = create(:system_node_module_version, node_module: lone, version_number: 1)
        lone.update_columns(current_version_id: only.id, current_version_number: 1)

        post "/api/v1/system/node_modules/#{lone.id}/rollback", headers: headers

        expect(response).to have_http_status(:unprocessable_content)
        expect(JSON.parse(response.body)["error"]).to match(/previous|rollback/i)
      end

      # IMP-b7abf6c777da made this population REACHABLE. Before it,
      # ModuleVersionService#create_version repointed current_version_id at
      # every row it minted, so any edit to a versioned module left a
      # "current" for rollback_to_previous to start from. Now the pointer only
      # moves on an explicit promotion, so a module whose promotion was
      # WITHHELD (auto_promote opt-out, artifact floor, provenance verdict,
      # batch hold) accumulates version rows with a nil pointer — and the
      # default rollback 422s. That is the intended answer, not a regression:
      # nothing was ever served, so there is nothing to roll back FROM. The
      # operator's route is target_version_id, pinned below.
      it "422s when versions exist but none was ever promoted" do
        unpromoted = create(:system_node_module, account: account, node_platform: platform,
                            category: category, variety: "subscription", name: "unpromoted-mod")
        create(:system_node_module_version, node_module: unpromoted, version_number: 1)
        create(:system_node_module_version, node_module: unpromoted, version_number: 2)
        expect(unpromoted.reload.current_version_id).to be_nil

        post "/api/v1/system/node_modules/#{unpromoted.id}/rollback", headers: headers

        expect(response).to have_http_status(:unprocessable_content)
        expect(JSON.parse(response.body)["error"]).to match(/No current version/i)
        expect(unpromoted.reload.current_version_id).to be_nil
      end

      it "still rolls back by target_version_id when nothing was ever promoted" do
        unpromoted = create(:system_node_module, account: account, node_platform: platform,
                            category: category, variety: "subscription", name: "target-mod")
        target = create(:system_node_module_version, node_module: unpromoted, version_number: 1,
                        file_spec: { "a" => "1" })
        create(:system_node_module_version, node_module: unpromoted, version_number: 2,
               file_spec: { "b" => "2" })

        post "/api/v1/system/node_modules/#{unpromoted.id}/rollback",
             params: { target_version_id: target.id }.to_json, headers: headers

        expect(response).to have_http_status(:ok)
        expect(unpromoted.reload.file_spec).to eq({ "a" => "1" })
        # The rollback version — not the target itself — becomes current.
        expect(unpromoted.current_version_id).to eq(unpromoted.versions.order(:version_number).last.id)
      end
    end

    # IMP-01a02f50ce34 + IMP-01a02f59f44d — rollback is a config WRITER: it
    # restores version.config verbatim, and NodeModule#config ships to every
    # node carrying the module. Two gates, both via the SAME shared validator
    # the write paths use (System::ModuleConfigValidator):
    #   1. a snapshot whose config the gate now refuses (pre-gate history)
    #      must not be re-shipped;
    #   2. a snapshot lacking the module's CURRENT security/verify block (the
    #      CI-publication paths mint git_tag-only version rows) must not drop
    #      confinement silently — the operator states the intent with
    #      acknowledge_confinement_removal.
    # ORACLE: stored config unchanged after a refusal — a 422 alone would
    # pass against code that writes then reports failure.
    context "restored-config validation" do
      let(:confined_config) do
        {
          "security" => { "capabilities" => [ "CAP_CHOWN" ], "egress_allow" => [] },
          "verify" => { "probes" => [
            { "name" => "gh", "command" => "gh", "resolves_to" => "/usr/bin/gh" }
          ] }
        }
      end

      before { node_module.update_columns(config: confined_config) }

      it "422s rolling back to a snapshot the config gate now refuses, leaving stored config unchanged" do
        # Pre-gate shape: a verify probe with no resolves_to (an existence
        # check) — exactly what the write gate refuses today.
        bad = create(:system_node_module_version, node_module: node_module, version_number: 90,
                     config: { "verify" => { "probes" => [ { "name" => "gh", "command" => "gh" } ] } })

        post "/api/v1/system/node_modules/#{node_module.id}/rollback",
             params: { target_version_id: bad.id }.to_json, headers: headers

        expect(response).to have_http_status(:unprocessable_content)
        expect(JSON.parse(response.body)["error"]).to match(/no longer acceptable/)
        expect(node_module.reload.config).to eq(confined_config)
      end

      it "422s rolling back to a git_tag-only snapshot without the confinement-removal acknowledgement" do
        tag_only = create(:system_node_module_version, node_module: node_module, version_number: 91,
                          config: { "git_tag" => "1.2.3" })

        post "/api/v1/system/node_modules/#{node_module.id}/rollback",
             params: { target_version_id: tag_only.id }.to_json, headers: headers

        expect(response).to have_http_status(:unprocessable_content)
        expect(JSON.parse(response.body)["error"]).to match(/acknowledge_confinement_removal/)
        expect(node_module.reload.config).to eq(confined_config)
      end

      it "rolls back to that snapshot when the operator acknowledges the confinement removal" do
        tag_only = create(:system_node_module_version, node_module: node_module, version_number: 92,
                          config: { "git_tag" => "1.2.3" })

        post "/api/v1/system/node_modules/#{node_module.id}/rollback",
             params: { target_version_id: tag_only.id,
                       acknowledge_confinement_removal: true }.to_json, headers: headers

        expect(response).to have_http_status(:ok)
        expect(node_module.reload.config).to eq("git_tag" => "1.2.3")
      end

      it "needs no acknowledgement when the snapshot carries the module's confinement blocks" do
        full = create(:system_node_module_version, node_module: node_module, version_number: 93,
                      config: confined_config)

        post "/api/v1/system/node_modules/#{node_module.id}/rollback",
             params: { target_version_id: full.id }.to_json, headers: headers

        expect(response).to have_http_status(:ok)
        expect(node_module.reload.config).to eq(confined_config)
      end
    end

    context "permissions" do
      it "403s when the user lacks system.modules.update" do
        viewer = user_with_permissions("system.modules.read", account: account)
        viewer_headers = auth_headers_for(viewer).merge("Content-Type" => "application/json")

        post "/api/v1/system/node_modules/#{node_module.id}/rollback", headers: viewer_headers

        expect(response).to have_http_status(:forbidden)
      end
    end
  end
end
