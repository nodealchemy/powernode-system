# frozen_string_literal: true

require "rails_helper"

# IMP-c4235dad3779 — operator-facing versions list for the module detail
# version-lifecycle panel. Mirrors the worker_api versions action but on the
# operator surface (session auth + system.modules.read).
RSpec.describe "Operator API — Node Module versions list", type: :request do
  let(:account) { create(:account) }
  let(:other_account) { create(:account) }
  let(:user) { user_with_permissions("system.modules.read", account: account) }
  let(:headers) { auth_headers_for(user).merge("Content-Type" => "application/json") }

  let(:platform) { create(:system_node_platform, account: account) }
  let(:category) { create(:system_node_module_category, account: account) }
  let(:node_module) do
    create(:system_node_module, account: account, node_platform: platform,
           category: category, variety: "subscription", name: "versions-mod")
  end
  let!(:version_one) do
    create(:system_node_module_version, node_module: node_module, version_number: 1,
           promotion_state: "live")
  end
  let!(:version_two) do
    create(:system_node_module_version, node_module: node_module, version_number: 2,
           promotion_state: "built")
  end

  describe "GET /api/v1/system/node_modules/:id/versions" do
    it "lists versions newest-first with the module's current-version pointer" do
      node_module.update!(current_version: version_one)

      get "/api/v1/system/node_modules/#{node_module.id}/versions", headers: headers

      expect(response).to have_http_status(:ok)
      body = JSON.parse(response.body)
      versions = body.dig("data", "versions")
      expect(versions.map { |v| v["version_number"] }).to eq([2, 1])
      expect(versions.first).to include(
        "id" => version_two.id,
        "node_module_id" => node_module.id,
        "promotion_state" => "built"
      )
      expect(versions.first).to have_key("changelog")
      expect(versions.first).to have_key("oci_digest")
      expect(versions.first).to have_key("live_at")
      expect(body.dig("data", "current_version_id")).to eq(version_one.id)
      expect(body.dig("data", "current_version_number")).to eq(1)
    end

    it "returns an empty list for a module with no versions" do
      bare = create(:system_node_module, account: account, node_platform: platform,
                    category: category, variety: "subscription", name: "bare-mod")

      get "/api/v1/system/node_modules/#{bare.id}/versions", headers: headers

      expect(response).to have_http_status(:ok)
      body = JSON.parse(response.body)
      expect(body.dig("data", "versions")).to eq([])
      expect(body.dig("data", "current_version_id")).to be_nil
    end

    it "404s for another account's module" do
      foreign_platform = create(:system_node_platform, account: other_account)
      foreign_cat = create(:system_node_module_category, account: other_account)
      foreign_module = create(:system_node_module, account: other_account,
                              node_platform: foreign_platform, category: foreign_cat,
                              variety: "subscription", name: "foreign")

      get "/api/v1/system/node_modules/#{foreign_module.id}/versions", headers: headers

      expect(response).to have_http_status(:not_found)
    end

    it "403s without system.modules.read" do
      stranger = user_with_permissions("system.nodes.read", account: account)
      stranger_headers = auth_headers_for(stranger).merge("Content-Type" => "application/json")

      get "/api/v1/system/node_modules/#{node_module.id}/versions", headers: stranger_headers

      expect(response).to have_http_status(:forbidden)
    end
  end
end
