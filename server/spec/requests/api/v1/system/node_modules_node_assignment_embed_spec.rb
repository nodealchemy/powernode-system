# frozen_string_literal: true

require "rails_helper"

# IMP-3e9620967632 — the per-(node, module) toggle UI needs the assignment
# row (id/enabled/priority) alongside each module in the node-scoped index;
# NodeModuleAssignmentsController only exposes show + enable/disable by
# assignment id, so the node-scoped module list is the read path.
RSpec.describe "Operator API — Node Modules index node_assignment embed", type: :request do
  let(:account) { create(:account) }
  let(:user) { user_with_permissions("system.modules.read", account: account) }
  let(:headers) { auth_headers_for(user).merge("Content-Type" => "application/json") }

  let(:node) { create(:system_node, account: account) }
  let(:node_module) { create(:system_node_module, account: account, name: "embed-mod") }
  let!(:assignment) do
    create(:system_node_module_assignment, node: node, node_module: node_module,
           enabled: true, priority: 7)
  end

  describe "GET /api/v1/system/node_modules?node_id=..." do
    it "embeds the node's assignment row on each module" do
      get "/api/v1/system/node_modules", params: { node_id: node.id }, headers: headers

      expect(response).to have_http_status(:ok)
      row = JSON.parse(response.body).dig("data", "node_modules")
                .find { |m| m["id"] == node_module.id }
      expect(row).not_to be_nil
      expect(row["node_assignment"]).to include(
        "id" => assignment.id,
        "enabled" => true,
        "priority" => 7
      )
    end

    it "reflects a disabled assignment" do
      assignment.update!(enabled: false)

      get "/api/v1/system/node_modules", params: { node_id: node.id }, headers: headers

      row = JSON.parse(response.body).dig("data", "node_modules")
                .find { |m| m["id"] == node_module.id }
      expect(row.dig("node_assignment", "enabled")).to be false
    end

    it "omits node_assignment on the catalog-wide index (no node_id)" do
      get "/api/v1/system/node_modules", headers: headers

      row = JSON.parse(response.body).dig("data", "node_modules")
                .find { |m| m["id"] == node_module.id }
      expect(row).not_to be_nil
      expect(row).not_to have_key("node_assignment")
    end
  end
end
