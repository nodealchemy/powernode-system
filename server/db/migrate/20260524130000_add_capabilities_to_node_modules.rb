# frozen_string_literal: true

# Add a queryable capabilities array to NodeModule.
#
# Until now, the `dependencies.provides` block in each module's manifest.yaml
# was stored only inside the raw manifest_yaml blob. It served as operator-
# facing documentation but had no behavioral effect — ManifestImportService's
# `resolve_dependencies` matched manifest.requires entries by `gitea_repo_full_name`
# OR `name` only. Modules couldn't declare "I depend on whatever module
# provides capability database.postgres" — they had to pin to a specific
# module name like `powernode/postgres-primary`.
#
# This migration adds a denormalized JSONB column on NodeModule that
# ManifestImportService can populate at import time. resolve_dependencies
# then handles a new `capability:<tag>[@<constraint>]` syntax in requires:
# entries — looks up the highest-priority NodeModule whose capabilities
# array contains a matching entry, applies the optional semver constraint,
# returns it as the resolved dependency.
#
# Storage shape: JSONB array of strings. Each entry is either bare `<tag>`
# (e.g., "database.postgres") or `<tag>@<version>` (e.g.,
# "database.postgres@16"). The version suffix is parsed by Gem::Version
# at constraint-match time. Bare tags match any constraint that's also
# blank; constrained-resolves require a versioned provides entry.
#
# GIN index covers ?, ?|, ?&, @> operators — enough for the lookup path
# used by resolve_capability.
class AddCapabilitiesToNodeModules < ActiveRecord::Migration[8.0]
  def change
    add_column :system_node_modules, :capabilities, :jsonb,
               default: [], null: false,
               comment: "Capability tags this module provides (denormalized from manifest.dependencies.provides) — queried by ManifestImportService for capability:foo dependency resolution."

    add_index :system_node_modules, :capabilities, using: :gin,
              name: "idx_system_node_modules_on_capabilities_gin"
  end
end
