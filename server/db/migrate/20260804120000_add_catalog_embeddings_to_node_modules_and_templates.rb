# IMP-67aea0728774 — persisted embeddings for the module + template catalogs.
#
# The module-authoring runbook opens with a reuse-first gate ("does a module for
# this purpose already exist?") that had no machine surface: NodeModule and
# NodeTemplate carried no embedding, system_list_modules filtered by variety
# only, and system_list_templates took no parameters at all. The package catalog
# already solved the same problem (system_packages.embedding + HNSW cosine
# index, System::PackageSearchService, discover_packages_by_intent); this brings
# the same shape to the two catalogs an operator actually authors against.
#
# Deliberately NO embedding_started_at here, unlike system_packages. That column
# exists to arbitrate a FOR UPDATE SKIP LOCKED lease across concurrent worker
# batches over a 400k-row catalog. Module/template catalogs are three to four
# orders of magnitude smaller and are backfilled by a single bounded-batch rake
# pass (System::CatalogEmbeddingBackfillService), so a lease column would be
# dead weight. If this ever becomes worker-driven, add it then.
class AddCatalogEmbeddingsToNodeModulesAndTemplates < ActiveRecord::Migration[8.1]
  def change
    add_column :system_node_modules, :embedding, :vector, limit: 1536
    add_column :system_node_modules, :embedding_generated_at, :datetime

    add_column :system_node_templates, :embedding, :vector, limit: 1536
    add_column :system_node_templates, :embedding_generated_at, :datetime

    # Explicit name: required — the `using:` variant would otherwise collide
    # with the generated btree name on the same column (index-naming convention
    # in guidance-migrations-and-seeds).
    add_index :system_node_modules, :embedding,
              using: :hnsw, opclass: :vector_cosine_ops,
              name: "idx_system_node_modules_embedding_hnsw"
    add_index :system_node_templates, :embedding,
              using: :hnsw, opclass: :vector_cosine_ops,
              name: "idx_system_node_templates_embedding_hnsw"
  end
end
