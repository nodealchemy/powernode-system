# frozen_string_literal: true

# Per-module publish holdback. Defaults to TRUE so every existing module keeps
# today's auto-promote-on-publish behaviour exactly; this adds a lever, it does
# not change fleet policy.
#
# A DEDICATED COLUMN rather than a key on `config`, which was the obvious first
# choice and is wrong: `config` is in System::NodeModule::VERSIONED_ATTRIBUTES,
# so `update!(config: ...)` fires the after_update auto_create_version callback.
# Storing the flag there would mean that turning the holdback ON itself created
# a new module version — the precise event the holdback exists to withhold.
class AddAutoPromoteToSystemNodeModules < ActiveRecord::Migration[8.0]
  def change
    add_column :system_node_modules, :auto_promote, :boolean, default: true, null: false
  end
end
